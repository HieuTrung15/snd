"""Safe bulk transfer of Employees between rotating shift groups.

The tool deliberately changes only effective-dated Kíp membership and future
Shift Assignments generated by this engine. Manual assignments, raw check-ins,
final Attendance and Employee legacy fields are never changed.
"""

