@frappe.whitelist()
def preview_bulk_shift_group_transfer(
	employees,
	target_shift_group,
	effective_date,
	membership_end_date,
	generate_until=None,
	note=None,
):
	"""Return a read-only impact preview for a bulk Kíp transfer."""
	_require_transfer_role()
	request = _validate_request(
		employees,
		target_shift_group,
		effective_date,
		membership_end_date,
		generate_until,
		note,
	)
	_require_employee_access(request["employees"])
	preview = _build_preview(request)
	# Assignment names are an execution detail and can be numerous. Keep the
	# browser response compact; only the locked execution path needs this list.
	preview.pop("assignment_names_to_cancel", None)
	preview.pop("assignment_names_to_replace_today", None)
	return preview


@frappe.whitelist()
def execute_bulk_shift_group_transfer(
	employees,
	target_shift_group,
	effective_date,
	membership_end_date,
	generate_until=None,
	note=None,
):
	"""Execute immediately for small batches or queue larger transfers.

	The worker re-runs the complete preview while holding Employee row locks. A
	batch with any blocker is rejected before a business record is changed.
	"""
	_require_transfer_role()
	request = _validate_request(
		employees,
		target_shift_group,
		effective_date,
		membership_end_date,
		generate_until,
		note,
	)
	_require_employee_access(request["employees"])
	preview = _build_preview(request)
	_throw_if_blocked(preview)

	work_units = len(request["employees"]) * (
		(request["generate_until"] - request["effective_date"]).days + 1
	)
	if work_units <= 500:
		return _run_bulk_shift_group_transfer(request, requested_by=frappe.session.user)

	job_id = f"vnt-shift-group-transfer-{uuid4().hex}"
	frappe.enqueue(
		"vinatex.vnt_hr.shift_management.shift_group_transfer_service.run_queued_bulk_transfer",
		queue="long",
		timeout=3600,
		job_id=job_id,
		deduplicate=True,
		enqueue_after_commit=True,
		request=request,
		requested_by=frappe.session.user,
	)
	return {
		"status": "QUEUED",
		"job_id": job_id,
		"employees": len(request["employees"]),
		"message": _("The transfer was queued. You will be notified when it finishes."),
	}


def run_queued_bulk_transfer(request: dict, requested_by: str):
	"""RQ entry point that reports success/failure to the initiating HR user."""
	try:
		result = _run_bulk_shift_group_transfer(request, requested_by=requested_by)
	except Exception as exc:
		frappe.log_error(
			frappe.get_traceback(),
			"VNT Bulk Shift Group Transfer Failed",
			defer_insert=True,
		)
		frappe.publish_realtime(
			"vnt_bulk_shift_group_transfer_completed",
			{"status": "ERROR", "message": str(exc)},
			user=requested_by,
			# The failed business transaction must roll back, so an after-commit
			# callback would never run. Realtime publication itself is read-only.
			after_commit=False,
		)
		raise

	frappe.publish_realtime(
		"vnt_bulk_shift_group_transfer_completed",
		result,
		user=requested_by,
		after_commit=True,
	)
	return result


def _run_bulk_shift_group_transfer(request: dict, requested_by: str | None = None) -> dict:
	"""Atomically close/create memberships, cancel safe auto plans and regenerate."""
	# Do not pass the derived ``target_company`` key back into the public-input
	# validator. Queued jobs intentionally carry the normalized request so dates
	# and the target master are revalidated at execution time.
	request = _validate_request(
		request.get("employees"),
		request.get("target_shift_group"),
		request.get("effective_date"),
		request.get("membership_end_date"),
		request.get("generate_until"),
		request.get("note"),
	)
	_lock_employee_rows(request["employees"])
	preview = _build_preview(request)
	_throw_if_blocked(preview)

	# Cancel only records carrying both exact engine markers. Existing usage is
	# rejected by preview; a final locking read below catches usage committed
	# concurrently while this transaction is rebuilding the future plan.
	cancelled = 0
	for assignment_name in preview["assignment_names_to_cancel"]:
		assignment = frappe.get_doc("Shift Assignment", assignment_name)
		if not (
			cint(assignment.custom_generated_by_shift_group)
			and assignment.custom_assignment_source == AUTO_ASSIGNMENT_SOURCE
			and assignment.custom_shift_group != request["target_shift_group"]
		):
			frappe.throw(
				_("Shift Assignment {0} is no longer an eligible automatic assignment.").format(
					assignment_name
				)
			)
		assignment.flags.ignore_permissions = True
		assignment.cancel()
		cancelled += 1

	replaced_today = 0
	for assignment_name in preview.get("assignment_names_to_replace_today") or []:
		assignment = frappe.get_doc("Shift Assignment", assignment_name)
		if not (
			cint(assignment.custom_generated_by_shift_group)
			and assignment.custom_assignment_source == AUTO_ASSIGNMENT_SOURCE
			and assignment.custom_shift_group != request["target_shift_group"]
		):
			frappe.throw(
				_("Shift Assignment {0} is no longer an eligible automatic assignment.").format(
					assignment_name
				)
			)
		_cancel_current_day_assignment(assignment, request)
		replaced_today += 1

	membership_counts = Counter()
	for row in preview["rows"]:
		_apply_membership_change(row, request)
		membership_counts[row["membership_action"]] += 1

	generation = generate_shift_assignments(
		request["effective_date"],
		request["generate_until"],
		employees=request["employees"],
		shift_group=request["target_shift_group"],
		preview=False,
	)
	if generation.get("counts", {}).get("ERROR"):
		frappe.throw(
			_("Shift generation reported errors. The bulk transfer was rolled back; review Error Log.")
		)

	# A Checkin import does not lock the Employee row. Use a final locking read so
	# a log/Attendance committed while this batch was running forces a full
	# rollback, and a new matching insert cannot slip in before our commit.
	_assert_no_concurrent_usage(request["employees"], request)
	current_day_employees = [
		row["employee"] for row in preview["rows"] if row.get("has_current_day_checkins")
	]
	resynced = (
		cint(sync_checkin_shift_fields_for_date(getdate(today()), current_day_employees))
		if current_day_employees
		else 0
	)
	cache_sync = sync_employee_current_shift_groups(
		request["employees"],
		getdate(today()),
	)

	return {
		"status": "COMPLETED",
		"employees": len(request["employees"]),
		"target_shift_group": request["target_shift_group"],
		"effective_date": request["effective_date"],
		"membership_end_date": request["membership_end_date"],
		"cancelled_auto_assignments": cancelled,
		"current_day_assignments_replaced": replaced_today,
		"current_day_checkins_resynced": resynced,
		"membership_actions": dict(membership_counts),
		"generation_counts": generation.get("counts", {}),
		"employee_cache_counts": cache_sync.get("counts", {}),
		"requested_by": requested_by,
	}


def _cancel_current_day_assignment(assignment, request: dict):
	"""Cancel today's automatic row without HRMS ``on_cancel``.

	HRMS refuses to cancel an assignment while a same-day Checkin carries its
	Shift Type. Today's punches stay raw logs and are re-pointed to the
	regenerated target shift, so the Comment keeps the replaced plan for audit.
	"""
	before = {
		fieldname: assignment.get(fieldname)
		for fieldname in (
			"name",
			"employee",
			"shift_type",
			"start_date",
			"end_date",
			"status",
			"docstatus",
			"custom_assignment_source",
			"custom_shift_group",
			"custom_generated_by_shift_group",
			"custom_schedule_date",
		)
	}
	payload = {
		"summary": "Current-day automatic assignment replaced by same-day Shift Group transfer",
		"target_shift_group": request["target_shift_group"],
		"note": request["note"],
		"before": before,
	}
	frappe.get_doc(
		{
			"doctype": "Comment",
			"comment_type": "Info",
			"reference_doctype": "Shift Assignment",
			"reference_name": assignment.name,
			"content": f"<pre>{json.dumps(payload, ensure_ascii=False, default=str, sort_keys=True)}</pre>",
		}
	).insert(ignore_permissions=True)
	frappe.db.set_value(
		"Shift Assignment",
		assignment.name,
		{
			"docstatus": 2,
			"status": "Inactive",
			"modified": now_datetime(),
			"modified_by": frappe.session.user,
		},
		update_modified=False,
	)


def _apply_membership_change(row: dict, request: dict):
	action = row["membership_action"]
	current_name = row.get("current_membership")

	if action == "KEEP_MEMBERSHIP":
		return
	if action == "EXTEND_MEMBERSHIP":
		membership = frappe.get_doc("VNT Shift Group Assignment", current_name)
		membership.to_date = request["membership_end_date"]
		membership.note = _append_transfer_note(membership.note, request["note"])
		membership.save(ignore_permissions=True)
		return

	if action in ("CLOSE_AND_CREATE", "INACTIVATE_AND_CREATE"):
		membership = frappe.get_doc("VNT Shift Group Assignment", current_name)
		if action == "CLOSE_AND_CREATE":
			membership.to_date = add_days(request["effective_date"], -1)
		else:
			# The old membership starts on the transfer date, so it has no valid
			# historical day to retain. Inactivate it instead of deleting it.
			membership.status = "Inactive"
		membership.note = _append_transfer_note(membership.note, request["note"])
		membership.save(ignore_permissions=True)

	_create_membership(row, request)


def _create_membership(row: dict, request: dict):
	frappe.get_doc(
		{
			"doctype": "VNT Shift Group Assignment",
			"employee": row["employee"],
			"employee_name": row["employee_name"],
			"company": row["company"],
			"shift_group": request["target_shift_group"],
			"from_date": request["effective_date"],
			"to_date": request["membership_end_date"],
			"status": "Active",
			"note": request["note"],
		}
	).insert(ignore_permissions=True)


def _append_transfer_note(existing: str | None, transfer_note: str) -> str:
	if not existing:
		return transfer_note
	return f"{existing}\n{transfer_note}"


def _build_preview(request: dict) -> dict:
	employees = _get_employee_rows(request["employees"])
	employee_names = [row.name for row in employees]
	memberships = _load_memberships(
		employee_names,
		request["effective_date"],
		request["membership_end_date"],
	)
	group_names = set(frappe.get_all("VNT Shift Group", pluck="name"))
	assignments = _load_shift_assignments(
		employee_names,
		request["effective_date"],
		request["membership_end_date"],
	)
	attendance_dates = _load_attendance_dates(
		employee_names,
		request["effective_date"],
		request["membership_end_date"],
	)
	checkin_dates = _load_checkin_dates(
		employee_names,
		request["effective_date"],
		request["membership_end_date"],
	)

	assignments_by_employee = defaultdict(list)
	for assignment in assignments:
		assignments_by_employee[assignment.employee].append(assignment)

	rows = []
	assignment_names_to_cancel = []
	assignment_names_to_replace_today = []
	for employee in employees:
		row = _preview_employee(
			employee,
			request,
			memberships.get(employee.name, []),
			assignments_by_employee.get(employee.name, []),
			attendance_dates.get(employee.name, set()),
			checkin_dates.get(employee.name, set()),
			group_names,
		)
		rows.append(row)
		assignment_names_to_cancel.extend(row.pop("assignment_names_to_cancel"))
		assignment_names_to_replace_today.extend(row.pop("assignment_names_to_replace_today"))

	counts = Counter(row["status"] for row in rows)
	return {
		"target_shift_group": request["target_shift_group"],
		"effective_date": request["effective_date"],
		"membership_end_date": request["membership_end_date"],
		"generate_until": request["generate_until"],
		"counts": dict(counts),
		"employees": len(rows),
		"auto_assignments_to_cancel": len(assignment_names_to_cancel),
		"manual_assignments_preserved": sum(row["manual_assignments_preserved"] for row in rows),
		"rows": rows,
		"assignment_names_to_cancel": assignment_names_to_cancel,
		"assignment_names_to_replace_today": assignment_names_to_replace_today,
	}


def _preview_employee(
	employee,
	request,
	memberships,
	assignments,
	attendance_dates,
	checkin_dates,
	group_names,
):
	blockers = []
	current_memberships = [
		row
		for row in memberships
		if getdate(row.from_date) <= request["effective_date"]
		and (not row.to_date or getdate(row.to_date) >= request["effective_date"])
	]
	if len(current_memberships) > 1:
		blockers.append(_("Multiple active Shift Group Assignments overlap the effective date."))
	current_membership = current_memberships[0] if len(current_memberships) == 1 else None

	other_overlaps = [
		row
		for row in memberships
		if row != current_membership
		and getdate(row.from_date) <= request["membership_end_date"]
		and (not row.to_date or getdate(row.to_date) >= request["effective_date"])
	]
	if other_overlaps:
		blockers.append(
			_("Future/overlapping membership must be resolved first: {0}").format(
				", ".join(row.name for row in other_overlaps)
			)
		)

	current_group, group_source = _resolve_current_group(employee, current_membership, group_names)
	membership_action = _membership_action(current_membership, request)
	authoritative_group = current_membership.shift_group if current_membership else None
	display_group = employee.get("custom_shift_group")

	if employee.company != request["target_company"]:
		blockers.append(_("Employee Company differs from the target Shift Group Company."))
	# Same-day transfer keeps today's raw punches: today's Attendance is built
	# later by the daily pipeline from the replaced plan. Any Attendance, or a
	# punch on a later date, still means the period is already in use.
	current_date = getdate(today()) if checkin_dates else None
	has_current_day_checkins = (
		current_date in checkin_dates and current_date not in attendance_dates
	)
	used_dates = attendance_dates | (checkin_dates - {current_date})
	if used_dates:
		formatted_dates = ", ".join(str(value) for value in sorted(used_dates)[:10])
		if len(used_dates) > 10:
			formatted_dates += _(" and {0} more").format(len(used_dates) - 10)
		blockers.append(
			_("Employee already has Checkin/Attendance in the transfer period: {0}.").format(formatted_dates)
		)

	auto_to_cancel = []
	replace_today = []
	manual_preserved = 0
	for assignment in assignments:
		is_engine = bool(
			cint(assignment.get("custom_generated_by_shift_group"))
			and assignment.get("custom_assignment_source") == AUTO_ASSIGNMENT_SOURCE
		)
		if not is_engine:
			manual_preserved += 1
			if (
				current_membership
				and current_membership.shift_group != request["target_shift_group"]
				and assignment.get("custom_shift_group") == current_membership.shift_group
			):
				blockers.append(
					_(
						"Manual Shift Assignment {0} is linked to the current Shift Group and must be reviewed first."
					).format(assignment.name)
				)
			continue
		if assignment.get("custom_shift_group") == request["target_shift_group"]:
			continue

		covered_dates = _covered_dates(
			assignment,
			request["effective_date"],
			request["membership_end_date"],
		)
		if has_current_day_checkins and current_date in covered_dates:
			if (
				getdate(assignment.start_date)
				== current_date
				== getdate(assignment.end_date or assignment.start_date)
			):
				replace_today.append(assignment.name)
			else:
				blockers.append(
					_(
						"Automatic Shift Assignment {0} covers several days and today already has Checkin."
					).format(assignment.name)
				)
			continue
		if not covered_dates & used_dates:
			auto_to_cancel.append(assignment.name)

	return {
		"employee": employee.name,
		"employee_name": employee.employee_name,
		"company": employee.company,
		"current_shift_group": current_group,
		"group_source": group_source,
		"authoritative_shift_group": authoritative_group,
		"display_shift_group": display_group,
		"display_mismatch": bool(
			authoritative_group and display_group != authoritative_group
		),
		"target_shift_group": request["target_shift_group"],
		"current_membership": current_membership.name if current_membership else None,
		"membership_action": membership_action,
		"auto_assignments_to_cancel": len(auto_to_cancel),
		"manual_assignments_preserved": manual_preserved,
		"status": "BLOCKED" if blockers else "READY",
		"blockers": blockers,
		"has_current_day_checkins": has_current_day_checkins,
		"assignment_names_to_cancel": auto_to_cancel,
		"assignment_names_to_replace_today": replace_today,
	}


def _membership_action(current_membership, request) -> str:
	if not current_membership:
		return "CREATE_MEMBERSHIP"
	if current_membership.shift_group == request["target_shift_group"]:
		if (
			not current_membership.to_date
			or getdate(current_membership.to_date) >= request["membership_end_date"]
		):
			return "KEEP_MEMBERSHIP"
		return "EXTEND_MEMBERSHIP"
	if getdate(current_membership.from_date) < request["effective_date"]:
		return "CLOSE_AND_CREATE"
	return "INACTIVATE_AND_CREATE"


def _resolve_current_group(employee, current_membership, group_names):
	if current_membership:
		return current_membership.shift_group, "VNT Shift Group Assignment"
	if employee.get("custom_shift_group") and employee.custom_shift_group in group_names:
		return employee.custom_shift_group, "Employee.custom_shift_group"
	if employee.default_shift and employee.default_shift in group_names:
		return employee.default_shift, "Employee.default_shift (legacy read-only)"
	return None, None


def _get_employee_rows(employee_names):
	fields = ["name", "employee_name", "company", "status", "default_shift"]
	if frappe.get_meta("Employee").has_field("custom_shift_group"):
		fields.append("custom_shift_group")
	rows = frappe.get_all(
		"Employee",
		filters={"name": ["in", employee_names]},
		fields=fields,
		order_by="name",
	)
	found = {row.name for row in rows}
	missing = sorted(set(employee_names) - found)
	if missing:
		frappe.throw(_("Employee not found: {0}").format(", ".join(missing)))
	inactive = [row.name for row in rows if row.status != "Active"]
	if inactive:
		frappe.throw(_("Only active Employees can be transferred: {0}").format(", ".join(inactive)))
	return rows


def _load_memberships(employee_names, from_date, to_date):
	rows = frappe.get_all(
		"VNT Shift Group Assignment",
		filters={
			"employee": ["in", employee_names],
			"status": "Active",
			"from_date": ["<=", to_date],
		},
		or_filters=[["to_date", ">=", from_date], ["to_date", "is", "not set"]],
		fields=["name", "employee", "shift_group", "company", "from_date", "to_date", "status"],
		order_by="employee asc, from_date asc",
	)
	result = defaultdict(list)
	for row in rows:
		result[row.employee].append(row)
	return result


def _load_shift_assignments(employee_names, from_date, to_date):
	fields = ["name", "employee", "start_date", "end_date", "shift_type", "docstatus", "status"]
	for fieldname in (
		"custom_assignment_source",
		"custom_shift_group",
		"custom_generated_by_shift_group",
	):
		if frappe.get_meta("Shift Assignment").has_field(fieldname):
			fields.append(fieldname)
	return frappe.get_all(
		"Shift Assignment",
		filters={
			"employee": ["in", employee_names],
			"start_date": ["<=", to_date],
			"docstatus": 1,
			"status": "Active",
		},
		or_filters=[["end_date", ">=", from_date], ["end_date", "is", "not set"]],
		fields=fields,
		order_by="employee asc, start_date asc",
	)


def _load_attendance_dates(employee_names, from_date, to_date, *, for_update=False):
	result = defaultdict(set)
	attendance = frappe.qb.DocType("Attendance")
	query = (
		frappe.qb.from_(attendance)
		.select(attendance.employee, attendance.attendance_date)
		.where(
			attendance.employee.isin(employee_names)
			& (attendance.attendance_date >= from_date)
			& (attendance.attendance_date <= to_date)
			& (attendance.docstatus < 2)
		)
	)
	if for_update:
		query = query.for_update()
	for row in query.run(as_dict=True):
		result[row.employee].add(getdate(row.attendance_date))
	return result


def _load_checkin_dates(employee_names, from_date, to_date, *, for_update=False):
	result = defaultdict(set)
	checkin = frappe.qb.DocType("Employee Checkin")
	query = (
		frappe.qb.from_(checkin)
		.select(checkin.employee, checkin.time, checkin.shift_start)
		.where(
			checkin.employee.isin(employee_names)
			& (checkin.time >= datetime.combine(from_date, time.min))
			& (checkin.time <= datetime.combine(to_date + timedelta(days=1), time.max))
			& (checkin.docstatus < 2)
		)
	)
	if for_update:
		query = query.for_update()
	for row in query.run(as_dict=True):
		# A linked check-in uses the shift start date. For an unlinked raw log we
		# conservatively use its calendar date and block same-day transfer.
		work_date = get_datetime(row.shift_start).date() if row.shift_start else get_datetime(row.time).date()
		if from_date <= work_date <= to_date:
			result[row.employee].add(work_date)
	return result


def _assert_no_concurrent_usage(employee_names, request):
	if not employee_names:
		return

	employee_names = sorted(employee_names)
	attendance_dates = _load_attendance_dates(
		employee_names,
		request["effective_date"],
		request["membership_end_date"],
		for_update=True,
	)
	checkin_dates = _load_checkin_dates(
		employee_names,
		request["effective_date"],
		request["membership_end_date"],
		for_update=True,
	)
	current_date = getdate(today())
	conflicts = []
	for employee in employee_names:
		used_dates = attendance_dates[employee] | (checkin_dates[employee] - {current_date})
		if used_dates:
			conflicts.append(f"{employee}: {', '.join(str(value) for value in sorted(used_dates))}")

	if conflicts:
		frappe.throw(
			_(
				"New Checkin/Attendance data appeared during the transfer. The whole batch was rolled back: {0}"
			).format("; ".join(conflicts[:10]))
		)


def _covered_dates(assignment, from_date, to_date):
	start = max(getdate(assignment.start_date), from_date)
	end = min(getdate(assignment.end_date) if assignment.end_date else to_date, to_date)
	if start > end:
		return set()
	return {start + timedelta(days=offset) for offset in range((end - start).days + 1)}


def _validate_request(
	employees,
	target_shift_group,
	effective_date,
	membership_end_date,
	generate_until=None,
	note=None,
):
	required_assignment_fields = {
		"custom_assignment_source",
		"custom_shift_group",
		"custom_generated_by_shift_group",
		"custom_schedule_date",
	}
	assignment_meta = frappe.get_meta("Shift Assignment")
	if not shift_management_schema_is_ready() or any(
		not assignment_meta.has_field(fieldname) for fieldname in required_assignment_fields
	):
		frappe.throw(_("Shift management schema is not installed."))

	if isinstance(employees, str):
		employees = frappe.parse_json(employees)
	if not isinstance(employees, (list, tuple)):
		frappe.throw(_("Employees must be a list."))
	employee_names = set()
	for row in employees:
		value = row.get("name") or row.get("employee") if isinstance(row, dict) else row
		if value:
			employee_names.add(value)
	employee_names = sorted(employee_names)
	if not employee_names:
		frappe.throw(_("Select at least one Employee."))
	if len(employee_names) > MAX_BULK_TRANSFER_EMPLOYEES:
		frappe.throw(_("A single transfer cannot exceed {0} Employees.").format(MAX_BULK_TRANSFER_EMPLOYEES))

	effective_date = getdate(effective_date)
	membership_end_date = getdate(membership_end_date)
	generate_until = getdate(generate_until or membership_end_date)
	if effective_date < getdate(today()):
		frappe.throw(_("Bulk transfer cannot be backdated. Use today or a future date."))
	if effective_date > membership_end_date:
		frappe.throw(_("Effective Date cannot be after Membership End Date."))
	if (membership_end_date - effective_date).days + 1 > MAX_MANUAL_GENERATION_DAYS:
		frappe.throw(_("Membership period cannot exceed {0} days.").format(MAX_MANUAL_GENERATION_DAYS))
	if not (effective_date <= generate_until <= membership_end_date):
		frappe.throw(_("Generate Until must be within the membership period."))
	if (generate_until - effective_date).days + 1 > MAX_MANUAL_GENERATION_DAYS:
		frappe.throw(_("Generation period cannot exceed {0} days.").format(MAX_MANUAL_GENERATION_DAYS))

	target_group = frappe.db.get_value(
		"VNT Shift Group",
		target_shift_group,
		["name", "company", "effective_from", "effective_to", "disabled"],
		as_dict=True,
	)
	if not target_group:
		frappe.throw(_("Target Shift Group does not exist."))
	if target_group.disabled:
		frappe.throw(_("Target Shift Group is disabled."))
	if target_group.effective_from and effective_date < getdate(target_group.effective_from):
		frappe.throw(_("Effective Date is before the target Shift Group period."))
	if target_group.effective_to and membership_end_date > getdate(target_group.effective_to):
		frappe.throw(_("Membership End Date is after the target Shift Group period."))
	if not (note or "").strip():
		frappe.throw(_("Reason/Note is required for audit."))

	return {
		"employees": employee_names,
		"target_shift_group": target_group.name,
		"target_company": target_group.company,
		"effective_date": effective_date,
		"membership_end_date": membership_end_date,
		"generate_until": generate_until,
		"note": (note or "").strip(),
	}


def _throw_if_blocked(preview):
	blocked = [row for row in preview["rows"] if row["status"] == "BLOCKED"]
	if not blocked:
		return
	details = []
	for row in blocked[:10]:
		details.append(f"{row['employee']}: {'; '.join(row['blockers'])}")
	frappe.throw(
		_("Bulk transfer has {0} blocked Employee(s):<br>{1}").format(
			len(blocked),
			"<br>".join(details),
		)
	)


def _require_transfer_role():
	frappe.only_for(("HR User", "HR Manager", "System Manager"))


def _require_employee_access(employee_names):
	denied = [
		employee for employee in employee_names if not frappe.has_permission("Employee", "read", doc=employee)
	]
	if denied:
		frappe.throw(
			_("You do not have permission to transfer these Employees: {0}").format(", ".join(denied[:10])),
			frappe.PermissionError,
		)
